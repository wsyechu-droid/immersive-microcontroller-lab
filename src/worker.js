const MODEL = '@cf/google/gemma-4-26b-a4b-it';

function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' },
  });
}

function extractJson(text) {
  const cleaned = String(text ?? '').replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '').trim();
  const start = cleaned.indexOf('{');
  const end = cleaned.lastIndexOf('}');
  if (start < 0 || end <= start) throw new Error('AI tidak menghasilkan objek JSON.');
  return JSON.parse(cleaned.slice(start, end + 1));
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === '/api/health' && request.method === 'GET') {
      return json({
        status: 'ok',
        genaiConfigured: Boolean(env.AI),
        provider: 'Cloudflare Workers AI',
        model: MODEL,
      });
    }

    if (url.pathname === '/api/generate' && request.method === 'POST') {
      let body;
      try {
        body = await request.json();
      } catch {
        return json({ error: 'Isi permintaan harus berupa JSON yang valid.' }, 400);
      }

      const { topic, difficulty, context, subject } = body ?? {};
      if (![topic, difficulty, context].every((v) => typeof v === 'string' && v.trim())) {
        return json({ error: 'topic, difficulty, dan context wajib diisi.' }, 400);
      }
      if (topic.length > 120 || difficulty.length > 40 || context.length > 180) {
        return json({ error: 'Input terlalu panjang.' }, 400);
      }
      if (!env.AI) {
        return json({ error: 'Workers AI binding belum diaktifkan pada konfigurasi Worker.' }, 503);
      }

      const prompt = [
        'Anda adalah perancang asesmen untuk mata kuliah Mikrokontroler dan Antarmuka tingkat diploma.',
        'Buat SATU soal pilihan ganda baru dalam Bahasa Indonesia. Soal harus akurat secara teknis, kontekstual, menguji penalaran atau penerapan, dan sesuai tingkat kesulitan.',
        'Keluarkan JSON valid saja tanpa markdown dengan bentuk:',
        '{"question":"...","options":["...","...","...","..."],"correctIndex":0,"explanation":"...","difficulty":"...","topic":"...","scenario":"..."}',
        'Ketentuan: tepat empat opsi; hanya satu jawaban benar; correctIndex bilangan bulat 0 sampai 3; jangan menambahkan teks di luar JSON.',
        `Mata kuliah: ${String(subject || 'Mikrokontroler dan Antarmuka')}`,
        `Topik: ${topic}`,
        `Kesulitan: ${difficulty}`,
        `Konteks penerapan: ${context}`,
        'Buat skenario latihan yang spesifik dan berbeda, jangan mengulang definisi umum.',
      ].join('\n');

      try {
        const result = await env.AI.run(MODEL, {
          prompt,
          max_tokens: 750,
          temperature: 0.35,
        });
        const text = typeof result === 'string'
          ? result
          : (result?.response ?? result?.output_text ?? '');
        const parsed = extractJson(text);
        if (
          typeof parsed.question !== 'string' ||
          !Array.isArray(parsed.options) || parsed.options.length !== 4 ||
          !Number.isInteger(parsed.correctIndex) || parsed.correctIndex < 0 || parsed.correctIndex > 3 ||
          typeof parsed.explanation !== 'string'
        ) {
          throw new Error('Struktur jawaban AI tidak sesuai format latihan.');
        }
        return json({ ...parsed, source: 'GENERATED BY CLOUDFLARE WORKERS AI' });
      } catch (error) {
        console.error('Workers AI generation error:', error);
        return json({ error: 'AI belum berhasil membuat latihan. Coba lagi atau periksa kuota dan konfigurasi Workers AI.' }, 502);
      }
    }

    if (url.pathname.startsWith('/api/')) {
      return json({ error: 'Endpoint API tidak ditemukan.' }, 404);
    }

    return env.ASSETS.fetch(request);
  },
};
